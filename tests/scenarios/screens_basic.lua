-- shared/screens.lua: touching monitor wins, the picker (tap or typed), the saved pick, resize/detach events.
local cc = require("sim.cc")
local T  = require("sim.test")

local function device(w, id, net, opts)
  opts = opts or {}
  local c = w:computer{ id = id, label = "C" .. id }
  if net then c:attach("back", cc.wired(net)) end
  for _, f in ipairs({ "shared/screens.lua", "shared/ui.lua", "shared/ui_widgets.lua", "shared/ui_parts.lua", "shared/ui_motion.lua" }) do c:install(f) end
  c:install("tests/demo/screens_stub.lua")
  c:writeTable("stub.cfg", { slots = opts.slots or { { id = "wall", label = "the main wall", required = false } } })
  return c
end
local function got(c, id) return c:output():match("got " .. id .. " (%S+)") end

T.test("screens: a touching monitor wins with no prompt and nothing saved", function()
  local w = cc.world()
  local net = w:net()
  net:monitor("monitor_1", 57, 24)
  local c = device(w, 1, net)
  local touching = c:monitor("right", 20, 10)
  c:monitor("left", 57, 24)
  c:run("screens_stub")
  w:run(5)
  T.eq(got(c, "wall"), "left", "the biggest touching monitor")
  T.falsy(c:readFile("monitors.cfg"), "nothing saved")
  T.absent(c.screen, "Pick")
  T.running(c)
end)

T.test("screens: no network monitor and none touching gives nil without a prompt", function()
  local w = cc.world()
  local net = w:net()
  local c = device(w, 1, net)
  c:run("screens_stub")
  w:run(5)
  T.eq(got(c, "wall"), "none")
  T.absent(c.screen, "Pick")
end)

T.test("screens: two network monitors are numbered, a tap picks, the other is blanked, a reboot remembers", function()
  local w = cc.world()
  local net = w:net()
  local m1 = net:monitor("monitor_1", 57, 24)
  local m2 = net:monitor("monitor_2", 15, 10)       -- a 1x1
  local c = device(w, 1, net)
  c:run("screens_stub")
  w:run(3)
  T.contains(c.screen, "Pick the main wall: tap a monitor or type its")
  T.contains(c.screen, "number")
  T.contains(c.screen, "1 monitor_1 (57x24)")
  T.contains(c.screen, "2 monitor_2 (15x10)")
  T.contains(c.screen, "Enter to skip")
  T.contains(m1, "Tap to pick the main wall")
  T.contains(m2, "Tap to pick the")           -- cut to fit a 1x1
  local lit = 0
  for y = 1, m2.h do for x = 1, m2.w do local _, b = m2:colourAt(x, y); if b ~= m2.bgs[1][1] then lit = lit + 1 end end end
  T.truthy(lit > 5, "the digit is drawn with background colour on a 1x1")
  m1:touch(10, 10)
  w:run(2)
  T.eq(got(c, "wall"), "monitor_1")
  T.eq(c:readFile("monitors.cfg"), "wall=monitor_1\n")
  T.eq(m2:text(), "", "the other candidate is blanked")
  T.absent(m1, "Tap to pick")
  -- reboot: same monitor, no prompt
  c:reboot()
  c:run("screens_stub")
  w:run(3)
  T.eq(got(c, "wall"), "monitor_1")
  T.absent(c.screen, "Pick")
  T.absent(m2, "Tap to pick")
end)

T.test("screens: a typed number picks too", function()
  local w = cc.world()
  local net = w:net()
  net:monitor("monitor_1", 57, 24)
  local m2 = net:monitor("monitor_2", 57, 24)
  local c = device(w, 1, net)
  c:run("screens_stub")
  w:run(3)
  c:type("2"); c:key(257)
  w:run(2)
  T.eq(got(c, "wall"), "monitor_2")
  T.eq(c:readFile("monitors.cfg"), "wall=monitor_2\n")
  T.absent(m2, "Tap to pick")
end)

T.test("screens: Enter skips an optional slot and the skip is remembered", function()
  local w = cc.world()
  local net = w:net()
  net:monitor("monitor_1", 57, 24)
  local c = device(w, 1, net)
  c:run("screens_stub")
  w:run(3)
  c:key(257)
  w:run(2)
  T.eq(got(c, "wall"), "none")
  c:reboot(); c:run("screens_stub"); w:run(3)
  T.absent(c.screen, "Pick")
end)

T.test("screens: a saved monitor that is gone asks again", function()
  local w = cc.world()
  local net = w:net()
  net:monitor("monitor_2", 57, 24)
  local c = device(w, 1, net)
  c:writeFile("monitors.cfg", "wall=monitor_9\n")
  c:run("screens_stub")
  w:run(3)
  T.contains(c.screen, "1 monitor_2")
  c:type("1"); c:key(257)
  w:run(2)
  T.eq(got(c, "wall"), "monitor_2")
  T.eq(c:readFile("monitors.cfg"), "wall=monitor_2\n")
end)

T.test("screens: slots are asked one at a time and a taken monitor is not offered again", function()
  local w = cc.world()
  local net = w:net()
  net:monitor("monitor_1", 57, 24)
  net:monitor("monitor_2", 15, 10)
  local c = device(w, 1, net, { slots = { { id = "wall", label = "the main wall" }, { id = "strip", label = "the light strip" } } })
  c:run("screens_stub")
  w:run(3)
  c:type("1"); c:key(257)
  w:run(3)
  T.contains(c.screen, "Pick the light strip")
  T.contains(c.screen, "1 monitor_2")
  T.absent(c.screen, "monitor_1")
  c:type("1"); c:key(257)
  w:run(2)
  T.eq(got(c, "strip"), "monitor_2")
  T.eq(c:readFile("monitors.cfg"), "wall=monitor_1\nstrip=monitor_2\n")
end)

T.test("screens: resize and detach of an owned monitor send screens_changed", function()
  local w = cc.world()
  local net = w:net()
  local m1 = net:monitor("monitor_1", 57, 24)
  local c = device(w, 1, net)
  c:writeFile("monitors.cfg", "wall=monitor_1\n")
  c:run("screens_stub")
  w:run(3)
  T.eq(got(c, "wall"), "monitor_1")
  m1:setSize(164, 81)
  w:run(1)
  T.contains(c:output(), "changed wall")
  T.eq(c.G.s.size.wall.w, 164, "re-measured")
  net:remove("monitor_1")
  w:run(1)
  T.eq(select(2, c:output():gsub("changed wall", "")), 2)
  T.running(c)
end)
