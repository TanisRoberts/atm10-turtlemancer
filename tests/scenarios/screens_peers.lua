-- shared/screens.lua: two computers on one cable never number or take the same monitor.
local cc = require("sim.cc")
local T  = require("sim.test")

local function device(w, id, net)
  local c = w:computer{ id = id, label = "C" .. id }
  c:attach("back", cc.wired(net))
  for _, f in ipairs({ "shared/screens.lua", "shared/ui.lua", "shared/ui_widgets.lua", "shared/ui_parts.lua", "shared/ui_motion.lua" }) do c:install(f) end
  c:install("tests/demo/screens_stub.lua")
  c:writeTable("stub.cfg", { slots = { { id = "wall", label = "wall " .. id } } })
  return c
end
local function got(c) return c:output():match("got wall (%S+)") end

T.test("screens: two computers picking at the same moment never share a monitor", function()
  local w = cc.world()
  local net = w:net()
  local m1, m2 = net:monitor("monitor_1", 57, 24), net:monitor("monitor_2", 57, 24)
  local a, b = device(w, 1, net), device(w, 2, net)
  a:run("screens_stub"); b:run("screens_stub")
  w:run(4)
  -- computer 1 (lower id) keeps both; computer 2 has nothing left to offer, so an optional slot is nil
  T.contains(m1, "Tap to pick wall 1")
  T.contains(m2, "Tap to pick wall 1")
  T.absent(m1, "wall 2")
  T.absent(m2, "wall 2")
  T.eq(got(b), "none")
  m2:touch(5, 5)
  w:run(3)
  T.eq(got(a), "monitor_2")
  T.eq(m1:text(), "", "the other candidate is blanked")
  T.running(b)
end)

T.test("screens: a computer starting later skips what a peer owns or is numbering", function()
  local w = cc.world()
  local net = w:net()
  local m1, m2, m3 = net:monitor("monitor_1", 57, 24), net:monitor("monitor_2", 57, 24), net:monitor("monitor_3", 57, 24)
  local a = device(w, 1, net)
  a:writeFile("monitors.cfg", "wall=monitor_1\n")
  a:run("screens_stub")
  w:run(3)
  T.eq(got(a), "monitor_1")
  local b = device(w, 2, net)
  b:run("screens_stub")
  w:run(3)
  T.contains(b.screen, "1 monitor_2")
  T.contains(b.screen, "2 monitor_3")
  T.absent(b.screen, "monitor_1")
  T.absent(m1, "Tap to pick")
  -- a third computer arrives while b is numbering
  local c = device(w, 3, net)
  c:run("screens_stub")
  w:run(3)
  T.eq(got(c), "none", "nothing left to offer an optional slot")
  T.absent(c.screen, "Pick")
end)

T.test("screens: a saved monitor now owned by a live peer counts as gone", function()
  local w = cc.world()
  local net = w:net()
  net:monitor("monitor_1", 57, 24)
  local m2 = net:monitor("monitor_2", 57, 24)
  local a = device(w, 1, net)
  a:writeFile("monitors.cfg", "wall=monitor_1\n")
  a:run("screens_stub")
  w:run(3)
  local b = device(w, 2, net)
  b:writeFile("monitors.cfg", "wall=monitor_1\n")      -- the same pick, by mistake
  b:run("screens_stub")
  w:run(3)
  T.eq(got(a), "monitor_1")
  T.contains(b.screen, "1 monitor_2")
  T.absent(b.screen, "monitor_1")
  b:type("1"); b:key(257)
  w:run(2)
  T.eq(got(b), "monitor_2")
  T.eq(b:readFile("monitors.cfg"), "wall=monitor_2\n")
end)
