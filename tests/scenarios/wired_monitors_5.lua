-- Architect, art and plastic pick their monitor off the cable with shared/screens.lua (#102): with none touching,
-- the cable monitor is numbered, a tap picks it, and the controller draws on it. `monitors` asks again.
local cc = require("sim.cc")
local T  = require("sim.test")

T.test("architect: no touching monitor, the cable one is picked by a tap and shows the map", function()
  local w = cc.world()
  local net = w:net()
  local cable = net:monitor("monitor_5", 36, 24)
  local a = w:computer{ id = 1, label = "Architect" }
  a:attach("top", cc.wireless{ ender = true })
  a:attach("back", cc.wired(net))
  local s = w:computer{ id = 2, label = "Weaver" }
  s:attach("top", cc.wireless{ ender = true })
  a:installRole("architect")
  s:install("tests/demo/weaver_stub.lua", "weaver_stub.lua")
  s:run("weaver_stub")
  a:run("architect")
  w:run(4)
  T.eq(a.error, nil)
  T.contains(cable, "Tap to pick the Architect map")
  cable:touch(10, 10)
  w:run(15)
  T.eq(a.error, nil)
  T.contains(cable, "Weaver-01 building")
  T.eq(a:readFile("monitors.cfg"), "wall=monitor_5\n")
  -- `monitors` forgets the pick; the reboot asks again
  a:type("monitors"); a:key(257); w:run(3)
  T.falsy((a:readFile("monitors.cfg") or ""):find("monitor_5", 1, true), "the pick is forgotten")
end)

T.test("architect: a touching monitor still wins with no prompt", function()
  local w = cc.world()
  local net = w:net()
  local cable = net:monitor("monitor_5", 36, 24)
  local a = w:computer{ id = 1, label = "Architect" }
  a:attach("top", cc.wireless{ ender = true })
  a:attach("back", cc.wired(net))
  local mon = a:monitor("right", 36, 24)
  local s = w:computer{ id = 2, label = "Weaver" }
  s:attach("top", cc.wireless{ ender = true })
  a:installRole("architect")
  s:install("tests/demo/weaver_stub.lua", "weaver_stub.lua")
  s:run("weaver_stub")
  a:run("architect")
  w:run(15)
  T.contains(mon, "Weaver-01 building")
  T.absent(cable, "Tap to pick")
  T.falsy(a:readFile("monitors.cfg"), "nothing saved")
end)

T.test("art: waits for a monitor, picks the one on the cable and draws on it", function()
  local w = cc.world()
  local net = w:net()
  local cable = net:monitor("monitor_7", 36, 24, { colour = true })
  local c = w:computer{ id = 1, label = "Art" }
  c:attach("top", cc.wireless{ ender = true })
  c:attach("back", cc.wired(net))
  c:installRole("art")
  c:run("art")
  w:run(4)
  T.eq(c.error, nil)
  T.contains(cable, "Tap to pick the art wall")
  cable:touch(10, 10)
  w:run(10)
  T.eq(c.error, nil)
  T.eq(c:readFile("monitors.cfg"), "wall=monitor_7\n")
  T.absent(cable, "Tap to pick")
end)

